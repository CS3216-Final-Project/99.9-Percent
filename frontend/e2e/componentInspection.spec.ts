    await expect(inspect.getByRole("button",{name:/Add server|Limit to/})).toHaveCount(0);
    await page.screenshot({path:testInfo.outputPath("database-inspected.png")});
    await inspect.getByRole("button",{name:"Close",exact:true}).click();
    await page.getByRole("button",{name:"Hint",exact:true}).click();
    await page.getByRole("dialog",{name:"Hint",exact:true}).getByRole("button",{name:"Got it",exact:true}).click();
    const gold=page.locator(".campaign-gold-attention");
    // A folded or peeked inspector offers its visible entry before its component shortcut.
    if (await gold.getAttribute("aria-expanded")==="false") await gold.click();
    await expect(gold).toHaveCount(1);await expect(gold).toHaveAccessibleName("Database");await gold.click();
    expect(await inspect.locator(".component-inspection-summary").innerText()).toBe(summary);
    await expect(gold).toHaveCount(1);await expect(gold).toHaveAccessibleName(/Upgrade database/);
    await expect(gold).toBeInViewport({ratio:1});await gold.click();
