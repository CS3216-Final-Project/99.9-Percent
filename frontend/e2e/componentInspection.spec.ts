test("Monitoring Hint completes its inspection and recalculates useful Run without a stale target",async({page,installClock})=>{
  await installClock();await page.route("**/api/**",r=>r.abort());
  let game=tick(act(spikeCompany(false),{type:"add_server"}),2);
  game=tick(act(game,{type:"scale_up",appId:"app-3"}),3);
  game=tick(act(game,{type:"set_routing",mode:"balanced",targets:["app-1","app-2","app-3"]}));
  game=untilOffset(game,8);expect(campaignAttention(game).target).toBe("monitoring");
  await seedSave(page,game);await page.goto("/");
  await page.getByRole("button",{name:"Continue company",exact:true}).click();await expectRoom(page);
  await page.clock.pauseAt(new Date(await page.evaluate(()=>Date.now())+1000));
  await page.getByRole("dialog",{name:"Chapter 4: Spike 1",exact:true}).getByRole("button",{name:"Got it",exact:true}).click();
  await page.getByRole("button",{name:"Hint",exact:true}).click();
  const hint=page.getByRole("dialog",{name:"Hint",exact:true});await expect(hint).toContainText("Check Monitoring");
  await hint.getByRole("button",{name:"Got it",exact:true}).click();
  const gold=page.locator(".campaign-gold-attention");await expect(gold).toHaveCount(1);await expect(gold).toHaveAccessibleName("Monitoring");
  await gold.click();const modal=page.getByRole("dialog",{name:"Monitoring inspected",exact:true});
  await expect(modal).toBeVisible();await expect(gold).toHaveCount(0);
  await modal.getByRole("button",{name:"Inspect details",exact:true}).click();
  await expect(modal.getByRole("region",{name:"Monitoring readings"})).toBeVisible();
  await modal.getByRole("button",{name:"Close",exact:true}).click();
  await page.getByRole("button",{name:"Hint",exact:true}).click();await hint.getByRole("button",{name:"Got it",exact:true}).click();
  await expect(gold).toHaveCount(1);await expect(gold).toHaveAccessibleName("Run");
  expect((await savedGame(page)).campaign!.step).toBe(game.campaign!.step);
});
